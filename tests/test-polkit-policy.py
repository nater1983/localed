"""Verify the shipped policy and configured installation manifest."""

import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET


source = Path(sys.argv[1])
build = Path(sys.argv[2])
policy = source / "data" / "org.freedesktop.locale1.policy"
actions = ET.parse(policy).getroot().findall("action")
expected_ids = {
    "org.freedesktop.locale1.set-locale",
    "org.freedesktop.locale1.set-keyboard",
}
assert len(actions) == len(expected_ids), "unexpected number of policy actions"
assert {action.get("id") for action in actions} == expected_ids
for action in actions:
    defaults = action.find("defaults")
    assert defaults is not None, action.get("id")
    assert defaults.findtext("allow_any") == "auth_admin"
    assert defaults.findtext("allow_inactive") == "auth_admin"
    assert defaults.findtext("allow_active") == "auth_admin_keep"

# intro-installed.json is generated by Meson during configuration.
with (build / "meson-info" / "intro-installed.json").open(encoding="utf-8") as f:
    installed = json.load(f)

destinations = [Path(path).name for path in installed.values()]
assert "org.freedesktop.locale1.policy" in destinations, "policy missing from install"
assert "org.freedesktop.locale1.rules" not in destinations, "obsolete rule installed"
assert not (source / "data" / "org.freedesktop.locale1.rules.in").exists()
print("Polkit authentication defaults and installation manifest verified.")
